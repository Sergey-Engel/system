class RestoreTests(unittest.TestCase):
    def verify(self, entries, records=None, limit=backup.MAX_BYTES):
        with tempfile.TemporaryDirectory() as tmp:
            path = Path(tmp).resolve() / "archive.tar.gz"
            with tarfile.open(path, "w:gz") as archive:
                for member, payload in entries:
                    archive.addfile(member, io.BytesIO(payload) if payload is not None else None)
            return backup.verify_restore(path, records or {"safe": {"size": 3, "sha256": backup.digest(b"abc")}}, limit)

    def regular(self, name="safe", data=b"abc"):
        member = tarfile.TarInfo(name)
        member.size = len(data)
        return member, data

    def test_materializes_and_hashes_regular_bytes(self):
        with mock.patch.object(tarfile.TarFile, "extract", side_effect=AssertionError("unsafe extraction")), \
             mock.patch.object(tarfile.TarFile, "extractall", side_effect=AssertionError("unsafe extraction")):
            self.assertEqual(self.verify([self.regular()]), 1)

    def test_rejects_every_link_special_and_directory(self):
        for kind in (tarfile.SYMTYPE, tarfile.LNKTYPE, tarfile.CHRTYPE, tarfile.BLKTYPE, tarfile.FIFOTYPE, tarfile.DIRTYPE):
            with self.subTest(kind=kind):
                member = tarfile.TarInfo("safe")
                member.type, member.linkname = kind, "/outside"
                with self.assertRaises(backup.BackupError):
                    self.verify([(member, None)])

    def test_rejects_traversal_duplicates_unlisted_and_missing(self):
        for name in ("../safe", "/safe", "a/../safe", "a//safe", "./safe", "evil\\safe", "other"):
            with self.subTest(name=name), self.assertRaises(backup.BackupError):
                self.verify([self.regular(name)])
        with self.assertRaises(backup.BackupError):
            self.verify([self.regular(), self.regular()])
        with self.assertRaises(backup.BackupError):
            self.verify([])

    def test_hash_size_and_expanded_limit_checks(self):
        for payload in (b"wrong", b"xyz"):
            with self.subTest(payload=payload), self.assertRaises(backup.BackupError):
                self.verify([self.regular(data=payload)])
        with self.assertRaises(backup.BackupError):
            self.verify([self.regular()], limit=2)


class RouterTests(unittest.TestCase):
    def setUp(self):
        self.process = mock.patch.object(backup.subprocess, "Popen", side_effect=AssertionError("SSH forbidden")).start()
        self.read = mock.patch.object(backup, "bounded_read", side_effect=[json.dumps(IDENTITY).encode(), EXPORT, json.dumps(IDENTITY).encode()]).start()
        self.addCleanup(mock.patch.stopall)

    def test_one_router_export_fresh_identity_before_and_after(self):
        with mock.patch.object(backup.time, "monotonic", return_value=100):
            report, data = backup.fresh_router_export()
        self.assertEqual(report["status"], "FRESH_READONLY_EXPORT")
        self.assertEqual(data, EXPORT)
        self.assertEqual(self.read.call_count, 3)
        calls = self.read.call_args_list
        self.assertEqual(calls[0].args[1], 129)
        self.assertEqual(calls[1].args[1], 129)
        self.assertEqual(calls[2].args[1], 129)
        args = calls[1].args[0]
        self.assertEqual(args[-2:], ["codex@10.30.30.2", "/export terse show-sensitive"])
        for value in ("HostKeyAlias=192.168.88.1", "ControlPath=none", "ConnectionAttempts=1", "StrictHostKeyChecking=yes"):
            self.assertIn(value, args)
        self.assertTrue(any(arg.endswith("/.local/ssh/codex_mikrotik_20260704") for arg in args))
        proxy = next(arg for arg in args if arg.startswith("ProxyCommand="))
        self.assertIn("docker inspect", proxy)
        self.assertIn("nsenter", proxy)
        self.assertIn("/proc/$$/fd/3", proxy)
        self.assertIn("nc -w", proxy)
        self.assertIn("%%s", proxy)
        self.assertNotRegex(proxy.replace("%%", ""), "%")
        for forbidden in ("stage9", "manifest", "systemctl", "wg set", "nft -f", "file=", "/system backup"):
            self.assertNotIn(forbidden, " ".join(args))
        self.process.assert_not_called()

    def test_proxy_shell_quoting_retains_identity_and_readonly_commands(self):
        args = backup.router_args(IDENTITY, 18)
        proxy = next(arg for arg in args if arg.startswith("ProxyCommand="))
        local_shell_args = shlex.split(proxy.removeprefix("ProxyCommand=").replace("%%", "%"))
        remote_shell_args = shlex.split(local_shell_args[-1])
        self.assertEqual(remote_shell_args[:5], ["timeout", "--kill-after=1s", "18s", "bash", "-c"])
        script = remote_shell_args[5]
        self.assertIn('exec 3<"/proc/$pid/ns/net"', script)
        self.assertIn('current=$(printf', script)
        self.assertIn('[ "$current" = ', script)
        expected = json.dumps(IDENTITY, sort_keys=True, separators=(",", ":"))
        self.assertIn(shlex.quote(expected), script)
        self.assertIn('exec nsenter --net="/proc/$$/fd/3" -- nc -w 18 10.30.30.2 22', script)

    def test_router_failure_is_not_retried_or_replaced_by_old_export(self):
        self.read.side_effect = [json.dumps(IDENTITY).encode(), backup.BackupError("router_timeout")]
        report, data = backup.fresh_router_export()
        self.assertEqual(report["status"], "FAILED")
        self.assertIsNone(data)
        self.assertTrue(report["old_export_is_not_fresh"])
        self.assertEqual(self.read.call_count, 2)

    def test_no_router_attempt_after_identity_failure(self):
        self.read.side_effect = OSError(SECRET.decode())
        report, data = backup.fresh_router_export()
        self.assertEqual(self.read.call_count, 1)
        self.assertEqual(report["status"], "FAILED")
        self.assertIsNone(data)
        self.assertNotIn(SECRET.decode(), json.dumps(report))

    def test_namespace_or_container_generation_change_invalidates_export(self):
        for key, value in (("namespace", "net:[999]"), ("pid", 999), ("id", "c" * 64),
                           ("started", "2026-09-13T12:01:00Z"), ("image", "sha256:" + "d" * 64)):
            with self.subTest(key=key):
                changed = {**IDENTITY, key: value}
                self.read.side_effect = [json.dumps(IDENTITY).encode(), EXPORT, json.dumps(changed).encode()]
                report, data = backup.fresh_router_export()
                self.assertEqual(report["reason"], "router_namespace_changed")
                self.assertIsNone(data)

    def test_invalid_identity_and_export_are_sanitized(self):
        for data in (b"[]", b"null", SECRET, json.dumps({**IDENTITY, "pid": True}).encode()):
            self.read.side_effect = [data]
            report, export = backup.fresh_router_export()
            self.assertEqual(report["status"], "FAILED")
            self.assertIsNone(export)
            self.assertNotIn(SECRET.decode(), json.dumps(report))
        for data in (SECRET, b"failure: denied", b"# by RouterOS\n#error exporting\n/ip address\n",
                     EXPORT + b"# error exporting section\n", EXPORT + b"# interrupted\n"):
            self.read.side_effect = [json.dumps(IDENTITY).encode(), data]
            report, export = backup.fresh_router_export()
            self.assertEqual(report["status"], "FAILED")
            self.assertIsNone(export)


class RunnerAndImportTests(unittest.TestCase):
    def test_completed_child_cleanup_permission_race_keeps_success(self):
        child = mock.Mock(pid=123)
        child.stdout.fileno.return_value = 456
        child.wait.return_value = 0
        child.poll.return_value = 0
        with mock.patch.object(backup.subprocess, "Popen", return_value=child), \
                mock.patch.object(backup.selectors, "DefaultSelector") as selector, \
                mock.patch.object(backup.os, "read", side_effect=[b"safe\n", b""]), \
                mock.patch.object(backup.os, "killpg", side_effect=PermissionError):
            selector.return_value.__enter__.return_value.select.return_value = [True]
            self.assertEqual(backup.bounded_read(["synthetic"], time.monotonic() + 3, 2, 100), b"safe\n")
        child.stdout.close.assert_called_once()

    def test_live_child_cleanup_permission_error_is_not_hidden(self):
        child = mock.Mock(pid=123)
        child.stdout.fileno.return_value = 456
        child.wait.return_value = 0
        child.poll.return_value = None
        with mock.patch.object(backup.subprocess, "Popen", return_value=child), \
                mock.patch.object(backup.selectors, "DefaultSelector") as selector, \
                mock.patch.object(backup.os, "read", return_value=b""), \
                mock.patch.object(backup.os, "killpg", side_effect=PermissionError):
            selector.return_value.__enter__.return_value.select.return_value = [True]
            with self.assertRaises(PermissionError):
                backup.bounded_read(["synthetic"], time.monotonic() + 3, 2, 100)
        child.stdout.close.assert_called_once()

    def test_import_is_inert_and_only_imports_run_backup_locally(self):
        path = ROOT / "backup_local.py"
        with mock.patch.object(backup.subprocess, "Popen", side_effect=AssertionError("import executed process")):
            spec = importlib.util.spec_from_file_location("backup_local_import_test", path)
            spec.loader.exec_module(importlib.util.module_from_spec(spec))
        tree = ast.parse(path.read_text())
        imports = [alias.name for node in ast.walk(tree) if isinstance(node, ast.Import) for alias in node.names
                   if (ROOT / (alias.name + ".py")).exists()]
        self.assertEqual(imports, ["run_backup"])

    def test_bounded_reader_with_local_synthetic_processes_only(self):
        def local_only(args, **kwargs):
            if args[:3] != [sys.executable, "-B", "-c"]:
                raise AssertionError("Non-local subprocess prohibited")
            return REAL_POPEN(args, **kwargs)
        with mock.patch.object(backup.subprocess, "Popen", side_effect=local_only):
            args = [sys.executable, "-B", "-c", "print('local-only')"]
            self.assertEqual(backup.bounded_read(args, time.monotonic() + 3, 2, 100), b"local-only\n")
            with self.assertRaisesRegex(backup.BackupError, "router_output_limit"):
                backup.bounded_read(args, time.monotonic() + 3, 2, 1)
            args[-1] = "import time; time.sleep(3)"
            start = time.monotonic()
            with self.assertRaisesRegex(backup.BackupError, "router_timeout"):
                backup.bounded_read(args, start + 0.1, 0.1, 100)
            self.assertLess(time.monotonic() - start, 2)


